/**
 * Clona schema do B1 → B2 (tabelas public da app + funções customizadas).
 * Não copia dados. Não toca em tabelas do sistema/PostGIS.
 *
 * Uso: node scripts/cluster/phase0-clone-schema.js
 */
import './loadEnvShim.js';
import pg from 'pg';

const { Client } = pg;

const SKIP_TABLES = new Set(['spatial_ref_sys']);

function requireEnv(name) {
  const value = (process.env[name] || '').trim();
  if (!value) {
    console.error(`❌ Variável ausente: ${name}`);
    process.exit(1);
  }
  return value;
}

function client(url) {
  return new Client({ connectionString: url, ssl: { rejectUnauthorized: false } });
}

async function listAppTables(primary) {
  const { rows } = await primary.query(`
    SELECT c.relname AS table_name
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relkind = 'r'
      AND NOT EXISTS (
        SELECT 1
        FROM pg_depend d
        JOIN pg_extension e ON d.refobjid = e.oid
        WHERE d.objid = c.oid AND d.deptype = 'e'
      )
    ORDER BY c.relname
  `);
  return rows.map((r) => r.table_name).filter((t) => !SKIP_TABLES.has(t));
}

async function buildCreateTableDDL(primary, tableName) {
  const cols = await primary.query(
    `
    SELECT
      a.attname AS column_name,
      pg_catalog.format_type(a.atttypid, a.atttypmod) AS data_type,
      a.attnotnull AS not_null,
      pg_get_expr(ad.adbin, ad.adrelid) AS column_default,
      a.attidentity AS identity
    FROM pg_attribute a
    JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
    WHERE n.nspname = 'public'
      AND c.relname = $1
      AND a.attnum > 0
      AND NOT a.attisdropped
    ORDER BY a.attnum
    `,
    [tableName]
  );

  if (cols.rows.length === 0) {
    throw new Error(`Tabela sem colunas: ${tableName}`);
  }

  const colDefs = cols.rows.map((col) => {
    let def = `"${col.column_name}" ${col.data_type}`;
    const isSerialDefault =
      col.column_default && /nextval\s*\(/i.test(col.column_default);

    if (col.identity === 'a') def += ' GENERATED ALWAYS AS IDENTITY';
    else if (col.identity === 'd' || isSerialDefault) {
      // SERIAL/nextval no B1 → IDENTITY no B2 (evita sequence ausente)
      def += ' GENERATED BY DEFAULT AS IDENTITY';
    } else if (col.column_default != null) {
      def += ` DEFAULT ${col.column_default}`;
    }
    if (col.not_null) def += ' NOT NULL';
    return def;
  });

  const pk = await primary.query(
    `
    SELECT a.attname AS column_name
    FROM pg_index i
    JOIN pg_class c ON c.oid = i.indrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = ANY (i.indkey)
    WHERE n.nspname = 'public'
      AND c.relname = $1
      AND i.indisprimary
    ORDER BY array_position(i.indkey, a.attnum)
    `,
    [tableName]
  );

  if (pk.rows.length) {
    const pkCols = pk.rows.map((r) => `"${r.column_name}"`).join(', ');
    colDefs.push(`PRIMARY KEY (${pkCols})`);
  }

  const quoted = `"${tableName.replace(/"/g, '""')}"`;
  return `CREATE TABLE public.${quoted} (\n  ${colDefs.join(',\n  ')}\n);`;
}

async function copyIndexes(primary, replica, tableName) {
  const { rows } = await primary.query(
    `
    SELECT indexname, indexdef
    FROM pg_indexes
    WHERE schemaname = 'public'
      AND tablename = $1
      AND indexname NOT IN (
        SELECT c2.relname
        FROM pg_index i
        JOIN pg_class c ON c.oid = i.indrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        JOIN pg_class c2 ON c2.oid = i.indexrelid
        WHERE n.nspname = 'public'
          AND c.relname = $1
          AND i.indisprimary
      )
    ORDER BY indexname
    `,
    [tableName]
  );

  for (const row of rows) {
    try {
      await replica.query(row.indexdef);
      console.log(`    index ${row.indexname} ✅`);
    } catch (err) {
      if (/already exists/i.test(err.message)) {
        console.log(`    index ${row.indexname} (já existe)`);
      } else {
        console.warn(`    index ${row.indexname} ⚠️ ${err.message}`);
      }
    }
  }
}

async function copyUniqueConstraints(primary, replica, tableName) {
  const { rows } = await primary.query(
    `
    SELECT con.conname, pg_get_constraintdef(con.oid) AS def
    FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relname = $1
      AND con.contype = 'u'
    ORDER BY con.conname
    `,
    [tableName]
  );

  const quoted = `"${tableName.replace(/"/g, '""')}"`;
  for (const row of rows) {
    try {
      await replica.query(
        `ALTER TABLE public.${quoted} ADD CONSTRAINT "${row.conname}" ${row.def}`
      );
      console.log(`    unique ${row.conname} ✅`);
    } catch (err) {
      if (/already exists/i.test(err.message)) {
        console.log(`    unique ${row.conname} (já existe)`);
      } else {
        console.warn(`    unique ${row.conname} ⚠️ ${err.message}`);
      }
    }
  }
}

async function listAppFunctions(primary) {
  const { rows } = await primary.query(`
    SELECT p.oid, p.proname AS name, pg_get_functiondef(p.oid) AS ddl
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public'
      AND p.prokind IN ('f', 'p')
      AND NOT EXISTS (
        SELECT 1
        FROM pg_depend d
        JOIN pg_extension e ON d.refobjid = e.oid
        WHERE d.objid = p.oid AND d.deptype = 'e'
      )
    ORDER BY p.proname, p.oid
  `);
  return rows;
}

async function main() {
  const primaryUrl = requireEnv('SUPABASE_DB_URL');
  const replicaUrl = requireEnv('SUPABASE_REPLICA_DB_URL');

  if (primaryUrl === replicaUrl) {
    console.error('❌ URLs B1 e B2 iguais. Abortado.');
    process.exit(1);
  }

  const primary = client(primaryUrl);
  const replica = client(replicaUrl);

  console.log('🔌 Conectando B1 e B2...');
  await primary.connect();
  await replica.connect();

  try {
    console.log('\n📦 Extensões no B2...');
    await replica.query('CREATE EXTENSION IF NOT EXISTS postgis');
    await replica.query('CREATE EXTENSION IF NOT EXISTS "uuid-ossp"');
    await replica.query('CREATE EXTENSION IF NOT EXISTS pgcrypto');
    console.log('  postgis / uuid-ossp / pgcrypto ✅');

    const tables = await listAppTables(primary);
    console.log(`\n📋 Tabelas app no B1 (${tables.length}): ${tables.join(', ')}`);

    for (const table of tables) {
      const quoted = `"${table.replace(/"/g, '""')}"`;
      process.stdout.write(`\n  → ${table} ... `);
      await replica.query(`DROP TABLE IF EXISTS public.${quoted} CASCADE`);
      const ddl = await buildCreateTableDDL(primary, table);
      await replica.query(ddl);
      console.log('criada ✅');
      await copyUniqueConstraints(primary, replica, table);
      await copyIndexes(primary, replica, table);

      // Grants típicos Supabase
      await replica.query(`GRANT ALL ON TABLE public.${quoted} TO postgres, anon, authenticated, service_role`);
      await replica.query(`GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO postgres, anon, authenticated, service_role`);
    }

    const functions = await listAppFunctions(primary);
    console.log(`\n🔧 Funções app no B1 (${functions.length}). Instalando no B2...\n`);

    let ok = 0;
    let fail = 0;
    for (const fn of functions) {
      process.stdout.write(`  → ${fn.name} ... `);
      try {
        await replica.query(fn.ddl);
        console.log('✅');
        ok += 1;
      } catch (err) {
        console.log(`❌ ${err.message}`);
        fail += 1;
      }
    }

    // Contagem final
    const b2Tables = await replica.query(`
      SELECT c.relname AS table_name
      FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = 'public' AND c.relkind = 'r'
        AND NOT EXISTS (
          SELECT 1 FROM pg_depend d
          JOIN pg_extension e ON d.refobjid = e.oid
          WHERE d.objid = c.oid AND d.deptype = 'e'
        )
      ORDER BY 1
    `);

    const { rows: triggers } = await primary.query(`
      SELECT
        c.relname AS table_name,
        t.tgname AS trigger_name,
        pg_get_triggerdef(t.oid, true) AS ddl
      FROM pg_trigger t
      JOIN pg_class c ON c.oid = t.tgrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = 'public'
        AND NOT t.tgisinternal
      ORDER BY 1, 2
    `);

    console.log(`\n⚡ Triggers no B1 (${triggers.length}). Instalando no B2...\n`);
    for (const row of triggers) {
      process.stdout.write(`  → ${row.table_name}.${row.trigger_name} ... `);
      try {
        await replica.query(row.ddl);
        console.log('✅');
      } catch (err) {
        if (/already exists/i.test(err.message)) console.log('(já existe)');
        else console.log(`❌ ${err.message}`);
      }
    }

    console.log('\n==============================');
    console.log(`Tabelas no B2: ${b2Tables.rows.map((r) => r.table_name).join(', ')}`);
    console.log(`Funções: ${ok} ok, ${fail} falha(s)`);
    console.log('✅ Clone de schema concluído (sem dados).');
    console.log('Próximo: npm run cluster:verify');
  } finally {
    await primary.end();
    await replica.end();
  }
}

main().catch((err) => {
  console.error('\n❌ Erro:', err.message);
  process.exit(1);
});
